export const getCounselorAutoReplyMessage = (studentName?: string, customText?: string): string => {
  if (customText && customText.trim()) {
    return customText.replace('{name}', studentName || '');
  }
  const nameGreeting = studentName ? `Hi ${studentName}! ` : 'Hi! ';
  return `${nameGreeting}অনুগ্রহ করে একটু অপেক্ষা করবেন। কিছুক্ষণের ভেতর আমাদের কাউন্সিলর সরাসরি আপনার সাথে লাইভ চ্যাটে যুক্ত হয়ে কথা বলবেন।`;
};
